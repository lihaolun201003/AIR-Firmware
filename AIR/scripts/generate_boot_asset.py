"""Export the supplied image as a compact 4-bit grayscale firmware bitmap.

The original PNG is kept verbatim. This is device-format conversion: the
whole image is fitted proportionally, with no tracing or character redraw.
Run from any directory: python scripts/generate_boot_asset.py
"""

from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/boot-character-original.png"
HEADER = ROOT / "include/boot_character_data.h"


def main():
    original = Image.open(SOURCE).convert("RGB")
    height = 208
    width = round(original.width * height / original.height)
    raster = original.resize((width, height), Image.Resampling.LANCZOS).convert("L")
    shades = [(value + 8) // 17 for value in raster.tobytes()]
    packed = bytes(
        (shades[i] << 4) | (shades[i + 1] if i + 1 < len(shades) else 15)
        for i in range(0, len(shades), 2)
    )
    lines = [
        "// Generated by scripts/generate_boot_asset.py; do not edit manually.",
        "#pragma once", "#include <stdint.h>", "",
        f"constexpr int16_t BOOT_CHARACTER_WIDTH = {width};",
        f"constexpr int16_t BOOT_CHARACTER_HEIGHT = {height};",
        "// Two grayscale pixels per byte, first pixel in the high nibble.",
        "static const uint8_t BOOT_CHARACTER_PIXELS[] = {",
    ]
    for start in range(0, len(packed), 16):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in packed[start:start + 16]) + ",")
    lines += ["};", ""]
    HEADER.write_text("\n".join(lines), encoding="ascii")
    print(f"Bitmap: {width} x {height}, {len(packed)} bytes in Flash")


if __name__ == "__main__":
    main()
